import { WEBUI_API_BASE_URL } from '$lib/constants';

export const verifyGoogleAIConnection = async (token: string = '', config: { url: string; key: string }) => {
	let error = null;

	const res = await fetch(`${WEBUI_API_BASE_URL}/googleai/verify`, {
		method: 'POST',
		headers: {
			Accept: 'application/json',
			'Content-Type': 'application/json',
			...(token && { authorization: `Bearer ${token}` })
		},
		body: JSON.stringify({
			...config
		})
	})
		.then(async (res) => {
			if (!res.ok) throw await res.json();
			return res.json();
		})
		.catch((err) => {
			console.error(err);
			if ('detail' in err) {
				error = err.detail;
			} else {
				error = 'Server connection failed';
			}
			return null;
		});

	if (error) {
		throw error;
	}

	return res;
};

